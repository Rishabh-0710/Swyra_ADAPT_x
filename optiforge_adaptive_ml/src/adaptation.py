"""
Dynamic Adaptation Controller: Translates drift analytics into calibrated
continual-learning schedules, sample reweighting, and specialist gating.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Any
import numpy as np
from src.drift import DriftReport


@dataclass
class AdaptationAction:
    """
    Decisions generated by the AdaptationController for an incoming batch.
    """
    adaptation_rate: float        # Normalized intensity in [0.10, 1.00]
    replay_blend_ratio: float     # Fraction of batch drawn from replay buffer
    specialist_weight: float      # Routing weight for the fast adaptive head
    anchor_weight: float          # Routing weight for the stable core trunk
    n_new_trees: int              # Number of boosting trees to allocate
    learning_rate: float          # Effective learning rate
    l2_regularization: float      # Effective L2 shrinkage penalty
    strategy_description: str     # Human-readable rationale


class AdaptationController:
    """
    Translates statistical drift diagnostics into controlled adaptation parameters,
    resolving the stability-plasticity dilemma on each sequential update.
    """

    def __init__(
        self,
        base_lr: float = 0.05,
        base_trees: int = 30,
        base_l2: float = 1.5,
    ) -> None:
        self.base_lr = base_lr
        self.base_trees = base_trees
        self.base_l2 = base_l2

    def compute_action(self, drift_report: DriftReport) -> AdaptationAction:
        """
        Dynamically schedule adaptation hyperparameters based on drift severity and nature.
        """
        severity = drift_report.severity
        score = drift_report.overall_drift_score
        is_concept = drift_report.is_concept_drift

        if severity == "none":
            # Conservative update: protect historical memory, low tree count
            adapt_rate = 0.15
            replay_ratio = 0.40
            specialist_w = 0.10
            n_trees = max(10, int(self.base_trees * 0.5))
            lr = self.base_lr * 0.8
            l2 = self.base_l2 * 1.5  # High regularization for stability
            desc = "Stationary distribution: conservative maintenance update with high replay."

        elif severity == "low":
            # Mild update
            adapt_rate = 0.30
            replay_ratio = 0.35
            specialist_w = 0.20
            n_trees = max(15, int(self.base_trees * 0.75))
            lr = self.base_lr * 0.9
            l2 = self.base_l2 * 1.2
            desc = "Low drift detected: modest parameter refinement with balanced replay."

        elif severity == "medium":
            # Balanced update
            adapt_rate = 0.60
            replay_ratio = 0.30
            specialist_w = 0.40
            n_trees = int(self.base_trees * 1.2)
            lr = self.base_lr * 1.15
            l2 = self.base_l2 * 1.0
            desc = "Moderate drift: balanced dual-memory update with increased capacity."

        else:  # severity == "high"
            # High plasticity required
            adapt_rate = 0.90 if not is_concept else 1.00
            # Under severe concept shift, reduce replay ratio slightly so new reality is captured
            replay_ratio = 0.20 if is_concept else 0.25
            specialist_w = 0.65 if is_concept else 0.50
            n_trees = int(self.base_trees * 1.8)
            lr = self.base_lr * (1.5 if is_concept else 1.3)
            l2 = self.base_l2 * 0.8  # Lower regularization for plasticity
            desc = (
                f"Severe {'concept' if is_concept else 'covariate'} shift detected: "
                "strong adaptation with specialist head dominance."
            )

        anchor_w = 1.0 - specialist_w

        return AdaptationAction(
            adaptation_rate=adapt_rate,
            replay_blend_ratio=replay_ratio,
            specialist_weight=specialist_w,
            anchor_weight=anchor_w,
            n_new_trees=n_trees,
            learning_rate=lr,
            l2_regularization=l2,
            strategy_description=desc,
        )
